function RootShell({ children }: { children: ReactNode }) {
  return (
    // The theme class is set by the inline script before React hydrates, so it differs from the server HTML.
    <html lang="en" suppressHydrationWarning>
      <head>
        {/* Runs before first paint: saved choice, else the OS setting. Avoids a light flash in dark mode. */}
        <script
          dangerouslySetInnerHTML={{
            __html: `try{var t=localStorage.getItem("theme");if(t==="dark"||(!t&&matchMedia("(prefers-color-scheme: dark)").matches))document.documentElement.classList.add("dark")}catch(e){}`,
          }}
        />
        <HeadContent />
        {/* Registers the service worker (installability + offline copy). Production only: it would cache dev assets. */}
        {import.meta.env.PROD && (
          <script
            dangerouslySetInnerHTML={{
              __html: `if("serviceWorker"in navigator)addEventListener("load",function(){navigator.serviceWorker.register("/sw.js")})`,
            }}
          />
        )}
      </head>
      <body>
        <WaveLines />
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
    </QueryClientProvider>
  );
}
